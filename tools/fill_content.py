     "<h2>从 PPO 说起：为什么贵</h2>"
     "<p>PPO 是 RLHF 的经典算法，它需要维护一个价值网络（critic）来估计每个状态的价值，从而算「优势」（advantage，衡量某个动作比平均好多少）。训 critic 本身就要占一份和策略网络差不多大的算力和显存，在大模型规模下这是很重的开销，而且 critic 估得不准则训练不稳。</p>"
