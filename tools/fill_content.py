def make_doc_json(slug, title, content_html):
    now = time.strftime("%Y-%m-%d %H:%M:%S")
    return {
        "_kind": "doc",
        "slug": slug,
        "title": title,
        "content": wrap(content_html),
        "format": "lake",
        "word_count": wc(content_html),
        "description": title,
        "updated_at": now,
        "created_at": now,
        "id": abs(hash(slug)) % 1000000,
        "status": 1,
    }


def main():
    # 1) 专题五：新建 _raw/docs + 追加 toc
    toc = json.load(open(TOC, encoding="utf-8"))
    existing_urls = {t.get("url") for t in toc if t.get("url")}
    new_entries = []
    prev_uuid = None
    for slug, title, html in DEEPSEEK:
        # 写文档
        path = os.path.join(DOCS, slug + ".json")
        if os.path.exists(path):
            d = json.load(open(path, encoding="utf-8"))
            d["content"] = wrap(html)
            d["title"] = title
            d["word_count"] = wc(html)
            json.dump(d, open(path, "w", encoding="utf-8"), ensure_ascii=False)
        else:
            json.dump(make_doc_json(slug, title, html), open(path, "w", encoding="utf-8"), ensure_ascii=False)
        # toc 条目
        if slug not in existing_urls:
            u = "ds" + _uuid.uuid4().hex[:14]
            entry = {
                "type": "DOC", "title": title, "uuid": u, "url": slug,
                "parent_uuid": ZHUANTI_WU, "doc_id": abs(hash(slug)) % 1000000,
                "level": 2, "id": abs(hash(slug)) % 1000000,
                "open_window": 1, "visible": 1,
                "child_uuid": "", "sibling_uuid": "",
            }
            new_entries.append(entry)
            if prev_uuid:
                for e in new_entries:
                    if e["uuid"] == prev_uuid:
                        e["sibling_uuid"] = u
            prev_uuid = u
    if new_entries:
        # 接到专题五 child_uuid 链头
        for t in toc:
            if t.get("uuid") == ZHUANTI_WU and not t.get("child_uuid"):
                t["child_uuid"] = new_entries[0]["uuid"]
        toc.extend(new_entries)
        json.dump(toc, open(TOC, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("专题五 新增文档:", len(new_entries))

    # 2) 专题八：填充空白文档内容
    filled = 0
    for slug, title, html in INDUSTRY:
        path = os.path.join(DOCS, slug + ".json")
        if os.path.exists(path):
            d = json.load(open(path, encoding="utf-8"))
        else:
            d = make_doc_json(slug, title, html)
        d["content"] = wrap(html)
        d["title"] = title
        d["word_count"] = wc(html)
        d["status"] = 1
        json.dump(d, open(path, "w", encoding="utf-8"), ensure_ascii=False)
        filled += 1
    print("专题八 填充文档:", filled)
    print("完成。下一步：python3 tools/build_data.py")


